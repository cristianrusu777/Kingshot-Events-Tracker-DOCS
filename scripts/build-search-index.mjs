import fs from 'node:fs'
import path from 'node:path'
import { publishedPages } from '../docs/.vitepress/publication-manifest.mts'
import { resolveSearchMetadata } from '../docs/.vitepress/search-metadata.mts'

const root = path.resolve(import.meta.dirname, '..')
const docsRoot = path.join(root, 'docs')

function stripMarkdown(value) {
  return value
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/<[^>]+>/g, ' ')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*_>#|{}]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

function bodyWithoutFrontmatter(source) {
  return source.replace(/^---\r?\n[\s\S]*?\r?\n---\r?\n/, '')
}

function sectionsFrom(source) {
  const body = bodyWithoutFrontmatter(source)
  const lines = body.split(/\r?\n/)
  const sections = []
  let heading = 'Introduction'
  let buffer = []
  const flush = () => {
    const text = stripMarkdown(buffer.join('\n'))
    if (text) sections.push({ heading, text: text.slice(0, 900) })
    buffer = []
  }
  for (const line of lines) {
    const match = /^(#{2,3})\s+(.+)$/.exec(line)
    if (match) {
      flush()
      heading = stripMarkdown(match[2])
    } else buffer.push(line)
  }
  flush()
  return sections
}

const records = publishedPages
  .filter((page) => page.product === 'kingshot-events')
  .map((page) => {
    const file = path.join(docsRoot, page.file)
    const sections = sectionsFrom(fs.readFileSync(file, 'utf8'))
    const metadata = resolveSearchMetadata(page)
    const introduction = sections.find((section) => section.heading === 'Introduction')?.text ?? sections[0]?.text ?? ''
    return {
      title: page.title,
      path: page.path,
      category: metadata.category,
      audience: page.audience,
      level: page.experienceLevel,
      contentType: metadata.contentType,
      featureArea: page.featureArea,
      aliases: metadata.aliases,
      description: introduction.slice(0, 240),
      sections
    }
  })

const output = `// Generated by scripts/build-search-index.mjs.\nexport const searchIndex = ${JSON.stringify(records, null, 2)} as const\n`
fs.writeFileSync(path.join(docsRoot, '.vitepress', 'generated-search-index.mts'), output)
console.log(`Search index written: ${records.length} published Kingshot Events guides.`)
